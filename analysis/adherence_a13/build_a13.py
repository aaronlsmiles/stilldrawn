#!/usr/bin/env python3
"""A13's two blind adherence studies: A9's instrument, rebuilt with new seeds and two repeats each.

    python analysis/adherence_a13/build_a13.py write
    python analysis/adherence_a13/build_a13.py check-locks
    python analysis/adherence_a13/build_a13.py check-build --study burst --dist analysis/adherence_a13/.build/a13-burst [--record [--replace-recorded] | --expect-recorded]

Nothing here is new wording. The question, scale labels, notes, intro lines, watch note and titles are
A9's constants, imported from analysis/adherence/prepare.py (frozen by the A9 manifest), and the study
files are written by A9's own builder (prepare.study_config). `blindpanel lock` on each A13 study must
give A9's study.lock.json (check-locks). The rating copies are A9's 110 files, hard-linked (copied where
a link is impossible) and checked against A9's media-sources.json; nothing is re-encoded.

What changes, and nothing else:
  - A13's own privacy line (PRIVACY, the line its consent page agrees with) in place of the kit's default,
    which A9 showed; blindpanel's wording hash leaves `privacy` out, so the lock is still A9's;
  - study ids a13-burst and a13-push and blinding seeds a13-burst-20261104 and a13-push-20261104, so
    every clip and panel code is new; `write` refuses if any equals an A9 code;
  - two attention repeats per study (blindpanel 0.3 parts.clips.repeats): the originals are the seeded
    draws random.Random("20261104:a13:burst:attention") and random.Random("20261104:a13:push:attention"),
    each .sample(the study's sorted public clip ids, 2), shown again at positions 30 and 52 of 57, each at least 5 places after its original; session_size 57.
The order each rater sees is not drawn here: the rating app derives one session per slot and
blindpanel derives the order from it (clip-rating-study tools/studies/a13.json).

A9's rating copies are gitignored, so a worktree has none: `write` reads them from the folder named by
$A13_A9_MEDIA (the main checkout's analysis/adherence), or from this repository's analysis/adherence if
its media are there, and refuses otherwise.

mapping.json (public ids, release-safe): per study the code of every clip and the repeats, the
attention clips and the attention rule; analysis/a13_adherence.py reads it.
"""
import argparse
import json
import os
import random
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
A9 = ROOT / "analysis" / "adherence"
MANIFEST = ROOT / "docs" / "A13-MANIFEST.sha256"     # exists from registration on: the trees are then frozen inputs
sys.path.insert(0, str(A9))
import prepare as P  # noqa: E402  (A9's instrument, frozen)

AMENDMENT = "A13"
SEED = 20261104
REPEAT_POSITIONS = (30, 52)
MIN_GAP = 5
N_CLIPS, N_REPEATS = 55, 2
ATTENTION_RULE = ("per study, an attention item fails when the repeat's score differs from the first "
                  "showing's by 2 or more points; a rater who fails both items of either study is excluded "
                  "from the whole analysis")
PRIVACY = ("This page sets one cookie and the hosting service logs page requests, as the consent page says. "
           "Pressing Send sends your answers, their order and a rounded duration under your study code.")
SPECS = {
    "burst": dict(P.BURST, id="a13-burst", seed="a13-burst-20261104"),
    "push": dict(P.PUSH, id="a13-push", seed="a13-push-20261104"),
}
HEAD = ("# Generated by build_a13.py for amendment A13 from A9's prepare.py. Do not edit by hand.\n"
        "# The wording is A9's: `blindpanel lock` must reproduce A9's study.lock.json (build_a13.py check-locks).\n")


A9_MEDIA_ENV = "A13_A9_MEDIA"


def attention_key(key):
    """The attention draw's seed string, as A13 registers it: "20261104:a13:burst:attention" and
    "20261104:a13:push:attention"."""
    return f"{SEED}:a13:{key}:attention"


def attention_ids(key, clip_ids):
    """The two repeated clips of a study: a seeded draw, declared in A13 before any rating."""
    return random.Random(attention_key(key)).sample(sorted(clip_ids), N_REPEATS)


def a9_media_root():
    """The folder holding A9's rating copies (<root>/burst/media, <root>/push/media). They are gitignored
    and live only in the main checkout, so a worktree names it in $A13_A9_MEDIA."""
    env = os.environ.get(A9_MEDIA_ENV)
    root = Path(env) if env else A9
    if not all((root / s["dir"] / "media").is_dir() for s in SPECS.values()):
        raise SystemExit(f"A9's rating copies are not under {root} (burst/media and push/media). They live only "
                         f"in the main checkout: set {A9_MEDIA_ENV} to its analysis/adherence folder; refusing")
    return root


def study_config(key, sources):
    """(blindpanel config, attention ids): A9's builder, then A13's privacy line (after the title), the
    repeats and their session size."""
    base = P.study_config(SPECS[key], sources)
    cfg = {}
    for k, v in base.items():
        cfg[k] = v
        if k == "title":
            cfg["privacy"] = PRIVACY
    att = attention_ids(key, sources["clips"])
    clips = cfg["parts"]["clips"]
    clips["session_size"] = N_CLIPS + N_REPEATS
    clips["repeats"] = {"min_gap": MIN_GAP,
                        "items": [{"of": a, "position": p} for a, p in zip(att, REPEAT_POSITIONS)]}
    return cfg, att


def link_media(key, sources):
    """Hard-link A9's rating copies (copy where a link is impossible) and check every one's hash."""
    spec = SPECS[key]
    src, dst = a9_media_root() / spec["dir"] / "media", HERE / spec["dir"] / "media"
    dst.mkdir(parents=True, exist_ok=True)
    recs = [*sources["clips"].values(), *sources["panels"].values()]
    for r in recs:
        name = Path(r["copy"]).name
        a, b = src / name, dst / name
        if not b.exists():
            try:
                os.link(a, b)
            except OSError:
                shutil.copy2(a, b)
        if P.sha256_file(b) != r["copy_sha256"]:
            raise SystemExit(f"{spec['dir']}/media/{name}: differs from A9's rating copy; refusing")
    return len(recs)


def mapping(configs, atts):
    studies = {}
    for key, cfg in configs.items():
        seed = SPECS[key]["seed"]
        ids = [c["id"] for c in cfg["items"]["clips"]]
        code = {i: P.opaque_code(seed, "clip", i) for i in ids}
        studies[key] = {
            "id": SPECS[key]["id"], "blinding_seed": seed, "question": SPECS[key]["question"]["id"],
            "code_to_cell": {code[i]: i for i in sorted(ids)},
            "repeats": [{"alias": P.opaque_code(seed, "clip", f"{a}#repeat"), "of": code[a], "position": p}
                        for a, p in zip(atts[key], REPEAT_POSITIONS)],
            "min_gap": MIN_GAP,
        }
    return {"instrument": AMENDMENT, "seed": SEED, "studies": studies,
            "attention_clips": {k: [r["of"] for r in s["repeats"]] for k, s in studies.items()},
            "attention_rule": ATTENTION_RULE,
            "code_scheme": ("blindpanel's seeded code: 'c' or 'p' plus five base32 characters from "
                            "sha256('<blinding seed>:code:<kind>:<id>'); a repeat's id is '<clip id>#repeat' "
                            "(blindpanel 0.3)")}


def a9_codes():
    out = set()
    for spec in (P.BURST, P.PUSH):
        src = json.loads((A9 / spec["dir"] / "media-sources.json").read_text())
        out |= {P.opaque_code(spec["seed"], "clip", c) for c in src["clips"]}
        out |= {P.opaque_code(spec["seed"], "panel", x) for x in src["panels"]}
    return out


def all_codes(m):
    out = set()
    for key, st in m["studies"].items():
        src = json.loads((A9 / SPECS[key]["dir"] / "media-sources.json").read_text())
        out |= set(st["code_to_cell"]) | {r["alias"] for r in st["repeats"]}
        out |= {P.opaque_code(SPECS[key]["seed"], "panel", x) for x in src["panels"]}
    return out


def motion_list():
    """Release paths of the 110 released motion files A13's motion AUC reads, for docs/A13-MANIFEST.list."""
    m = json.loads((HERE / "mapping.json").read_text())
    cells = sorted(c for st in m["studies"].values() for c in st["code_to_cell"].values())
    return [f"runs/metrics-motion/{c}.json" for c in cells]


def check_locks(missing_ok=False):
    """Each A13 study's study.lock.json (written by `blindpanel lock`) must equal A9's."""
    bad = []
    for spec in SPECS.values():
        mine, theirs = HERE / spec["dir"] / "study.lock.json", A9 / spec["dir"] / "study.lock.json"
        if not mine.exists():
            if not missing_ok:
                bad.append(f"{spec['id']}: no study.lock.json yet (run `blindpanel lock study.yaml`)")
            continue
        if json.loads(mine.read_text()) != json.loads(theirs.read_text()):
            bad.append(f"{spec['id']}: study.lock.json is not A9's: the wording is not A9's")
    if bad:
        raise SystemExit("\n".join(bad))


def write():
    configs, atts = {}, {}
    for key, spec in SPECS.items():
        sdir = HERE / spec["dir"]
        sdir.mkdir(exist_ok=True)
        shutil.copyfile(A9 / spec["dir"] / "media-sources.json", sdir / "media-sources.json")
        sources = json.loads((sdir / "media-sources.json").read_text())
        configs[key], atts[key] = study_config(key, sources)
        P.write_text(sdir / "study.yaml", HEAD + P.to_yaml(configs[key]) + "\n")
        P.write_text(sdir / "banned-terms.txt", P.BANNED_TERMS)
        n = link_media(key, sources)
        print(f"{spec['id']}: study.yaml, banned-terms.txt, media-sources.json; {n} rating copies linked and checked")
    m = mapping(configs, atts)
    clash = a9_codes() & all_codes(m)
    if clash:
        raise SystemExit(f"{len(clash)} A13 code(s) equal an A9 code; refusing to write mapping.json")
    P.write_json(HERE / "mapping.json", m)
    check_locks(missing_ok=True)
    print("mapping.json: 2 studies x 55 codes, 2 repeats each; no code equals an A9 code")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("command", choices=["write", "check-locks", "check-build", "motion-list"])
    ap.add_argument("--study", choices=sorted(SPECS))
    ap.add_argument("--dist")
    once = ap.add_mutually_exclusive_group()
    once.add_argument("--record", action="store_true")
    once.add_argument("--expect-recorded", action="store_true")
    ap.add_argument("--replace-recorded", action="store_true",
                    help="with --record: replace a different recorded tree (deliberately, before any rating)")
    a = ap.parse_args(argv)
    if a.replace_recorded and not a.record:
        ap.error("--replace-recorded belongs with --record")
    if a.replace_recorded and MANIFEST.exists():          # early exit; check_build_cli holds the guard
        refuse_replace_after_registration()
    if a.command == "write":
        write()
    elif a.command == "check-locks":
        check_locks()
        print("both studies' wording hashes equal A9's")
    elif a.command == "motion-list":
        print("\n".join(motion_list()))
    else:
        if not (a.study and a.dist):
            raise SystemExit("check-build needs --study and --dist")
        sys.exit(check_build_cli(a.study, Path(a.dist), a.record, a.expect_recorded, replace=a.replace_recorded))


def repeat_view(study, reveal, mst):
    """(problems, study view, reveal view). Checks the repeats against mapping.json's study entry `mst`:
    the session is 57 items and exactly 57 clip items are listed; each alias is listed once, its original
    once, and the alias item is its original's item with only the code changed (its original's clip beside
    its original's still, and nothing else, since A9's shape check never sees an alias); every scale is
    ordinal. Then returns study.json and reveal.json as A9's checks know them: the aliases, `repeats` and
    the scales' `kind` removed, session_size 55."""
    p = []
    if not isinstance(study, dict):
        return p, study, reveal
    clips = P._dig(study, "parts", "clips")
    clips = clips if isinstance(clips, dict) else {}
    items = clips.get("items") if isinstance(clips.get("items"), list) else []
    want = {"min_gap": mst["min_gap"],
            "items": [{"alias": r["alias"], "of": r["of"], "position": r["position"]} for r in mst["repeats"]]}
    if clips.get("repeats") != want:
        p.append("study.json: parts.clips.repeats differs from mapping.json")
    if clips.get("session_size") != N_CLIPS + N_REPEATS:
        p.append(f"study.json: session_size is not {N_CLIPS + N_REPEATS}")
    if len(items) != N_CLIPS + N_REPEATS:
        p.append(f"study.json: {len(items)} clip items, expected {N_CLIPS + N_REPEATS}")
    aliases = {r["alias"]: r["of"] for r in mst["repeats"]}
    listed = {}
    for i in items:
        if isinstance(i, dict):
            listed.setdefault(P._str(i.get("code")), []).append(i)
    for alias, of in aliases.items():
        a, o = listed.get(alias, []), listed.get(of, [])
        if len(a) != 1:
            p.append(f"study.json: repeat {alias} appears {len(a)} times, expected once")
        if len(o) != 1:
            p.append(f"study.json: the original of repeat {alias} appears {len(o)} times, expected once")
        elif any(x != dict(o[0], code=alias) for x in a):
            p.append(f"study.json: repeat {alias} is not its original's item with only the code changed "
                     "(its original's clip beside its original's still, and nothing else)")
    view = json.loads(json.dumps(study))
    vc = P._dig(view, "parts", "clips")
    if isinstance(vc, dict):
        vc.pop("repeats", None)
        if isinstance(vc.get("items"), list):
            vc["items"] = [i for i in vc["items"] if not (isinstance(i, dict) and i.get("code") in aliases)]
        vc["session_size"] = N_CLIPS
    for name, s in (view.get("scales") or {}).items():
        if s.get("kind") != "ordinal":
            p.append(f"study.json: scale {name} is not ordinal")
        s.pop("kind", None)
    rv = reveal
    if isinstance(reveal, dict) and isinstance(reveal.get("items"), dict):
        rv = json.loads(json.dumps(reveal))
        for alias in aliases:
            if rv["items"].pop(alias, None) != P.CLIP_REVEAL:
                p.append(f"reveal.json: repeat {alias} is missing or reveals something")
    return p, view, rv


def privacy_problems(study):
    """The built study.json must carry A13's privacy line, exactly."""
    if isinstance(study, dict) and study.get("privacy") == PRIVACY:
        return []
    return ["study.json: the privacy line is not A13's (build_a13.PRIVACY)"]


def check_build(key, dist, root=ROOT, tree="private", expect_tree=None):
    """(problems, tree hash, files scanned) for one built A13 study, A9's check_build in A13's form:
    the repeats checked by repeat_view, then A9's study.json, media, reveal and leak checks on the view,
    with A9's private terms added to the scan."""
    spec = SPECS[key]
    m = json.loads((HERE / "mapping.json").read_text())
    p = P.tree_problems(root, tree)
    dist = Path(dist)
    if not dist.is_dir():
        return p + [f"{dist}: is not a directory"], None, 0
    files, odd = P.dist_files(dist)
    p += odd
    if not files:
        p.append("the build is empty")
    b = P._load_build(spec, HERE / spec["dir"], dist)
    private, bad = P.load_private_terms()
    b.problems += bad
    b.terms += private or []
    rp = privacy_problems(b.study)
    vp, b.study, b.reveal = repeat_view(b.study, b.reveal, m["studies"][key])
    rp += vp
    rules = P.release_rules(root) if tree == "private" else None
    ids = [(i.lower(), f"cell, panel or engine id {i!r}")
           for i in [*b.clips, *b.panels, *P.ENGINES, *P.ENGINES.values()] if len(i) >= P.MIN_LITERAL]
    if rules:
        ids.append((rules.OLD_ID.lower(), "the private panel id"))
    sp, media = P._check_study_json(spec, b)
    mp, listed = P._check_media(dist, media)
    p += b.problems + rp + sp + mp + P._check_reveal(spec, b) + P._scan_files(dist, files, listed, b.terms, ids)
    tree_sha = P.tree_hash(dist)
    if expect_tree and tree_sha != expect_tree:
        p.append(f"build tree {tree_sha[:12]}… differs from the recorded {expect_tree[:12]}…")
    return p, tree_sha, len(files)


def refuse_replace_after_registration():
    raise SystemExit(f"{MANIFEST.name} exists: a recorded tree cannot be replaced after registration; refusing")


def check_build_cli(key, dist, record, expect_recorded, replace=False):
    spec = SPECS[key]
    expect = P.recorded_tree(spec, HERE) if expect_recorded else None
    problems, tree_sha, n = check_build(key, dist, expect_tree=expect)
    if problems:
        return P._fail(problems)
    print(f"{spec['id']}: clean ({n} files); tree {tree_sha}")
    if record:
        if replace and MANIFEST.exists():                 # the trees are frozen inputs once the manifest exists
            refuse_replace_after_registration()
        old = P.record_tree(spec, HERE, dist, tree_sha, replace=replace)
        print(f"recorded in build-trees.json{'' if old in (None, tree_sha) else f' (was {old})'}")
    return 0


if __name__ == "__main__":
    main()
