#!/usr/bin/env python3
"""Pre-registered analysis (docs/PREREGISTRATION.md §8, FROZEN) + descriptive tables.

Frozen elements executed here, exactly as registered:
  1. Per-engine x per-motion-class metric tables (headline scalars, mean ± range
     across panels).
  2. Content-class and treatment breakdowns.
  3. The pre-registered hypothesis test: establishing-environment panels degrade
     more than character/action panels on edge_decay |normalised slope| and
     style_drift terminal distance. One-sided Mann-Whitney U, establishing vs
     pooled other classes, per engine; alpha = 0.05; rank-biserial effect sizes;
     small-n caveat stated.

Analysis decisions NOT dictated by the frozen text (stated here, applied
uniformly, and reported in the paper):
  * Cell basis for the §8 test = the 33 standard cells per engine (27 frozen
    rotation + 6 A1 amendment cells; A1 is part of the registered protocol).
    The 6 H3-only FLINT cells are excluded from the test — they use first+last
    conditioning, which no other engine has, and §5 registers them as an
    H3-only extra ("recorded n/a for engines without first/last conditioning").
    They appear in the motion-class tables as their own row. Sensitivity run:
    the frozen-27 basis (pre-A1 rotation cells only) is reported alongside.
  * gen4_turbo has 32 cells: `cu-tone-3_idle` was refused twice (a result, not
    a gap — §5); the cell is absent, not imputed.
  * The grey-ground covariate look (paper_white_p90 vs headline scalars on
    line-only cells) is EXPLORATORY — it is not part of frozen §8 and is
    labelled as such in every output.

Outputs: analysis/out/tables.md, analysis/out/prereg_test.json,
         analysis/out/tables.json
"""
import json
from pathlib import Path

import numpy as np
from scipy import stats

OUT = Path(__file__).resolve().parent / "out"

HEADLINES = [
    ("line_chamfer_mean_px", "line_drift: mean chamfer vs f0 (px)"),
    ("tone_variance", "tone_spectral: band-energy variance"),
    ("edge_abs_slope", "edge_decay: |normalised slope|"),
    ("style_terminal", "style_drift: terminal distance"),
    ("closure_abs_terminal", "closure: |terminal drift|"),
]
ENGINES = ["gen4_turbo", "h3-fal", "gen4.5", "wan22", "ltx23"]  # report order
MOTIONS = ["IDLE", "BURST", "CAMPUSH", "FLINT"]
CLASSES = ["cu", "act", "est"]
TREATMENTS = ["line", "tone", "black", "ip-line+tone", "chain-black"]
ALPHA = 0.05


def load():
    rows = json.loads((OUT / "results_table.json").read_text())
    return rows


def vals(rows, metric):
    v = [r[metric] for r in rows if r[metric] is not None]
    return v


def fmt_cell(v):
    if not v:
        return "—"
    m = float(np.mean(v))
    return f"{m:.3g} [{min(v):.3g}–{max(v):.3g}] (n={len(v)})"


def group_table(rows, group_key, groups, metric):
    out = {}
    for g in groups:
        grows = [r for r in rows if r[group_key] == g]
        out[g] = vals(grows, metric)
    return out


def mwu_est_vs_rest(rows, metric):
    """One-sided MWU: establishing > pooled cu+act, on `metric` (frozen §8)."""
    est = vals([r for r in rows if r["content_class"] == "est"], metric)
    rest = vals([r for r in rows if r["content_class"] in ("cu", "act")], metric)
    if len(est) < 2 or len(rest) < 2:
        return None
    res = stats.mannwhitneyu(est, rest, alternative="greater", method="exact")
    u1 = float(res.statistic)
    n1, n2 = len(est), len(rest)
    rank_biserial = 2.0 * u1 / (n1 * n2) - 1.0    # +1 = est fully above rest
    return {
        "n_est": n1, "n_rest": n2,
        "U": u1, "p_one_sided": float(res.pvalue),
        "significant_at_0.05": bool(res.pvalue < ALPHA),
        "rank_biserial": rank_biserial,
        "median_est": float(np.median(est)),
        "median_rest": float(np.median(rest)),
    }


def main():
    rows = load()
    std = [r for r in rows if r["motion"] != "FLINT"]   # standard 33-cell basis

    md = ["# StillDrawn pre-registered analysis — tables",
          "",
          f"Generated by `analysis/prereg_stats.py` from `analysis/out/results_table.json` "
          f"({len(rows)} cells: {len(std)} standard + {len(rows)-len(std)} FLINT).",
          "Frozen protocol: `docs/PREREGISTRATION.md` §8. Cell values are "
          "mean [min–max] (n) of the headline scalar across cells.", ""]
    tables_json = {}

    # ---- 1. per-engine x per-motion ----------------------------------------
    md.append("## 1. Per-engine × per-motion-class (frozen §8 table 1)")
    for metric, label in HEADLINES:
        md += ["", f"### {label}", "",
               "| engine | " + " | ".join(MOTIONS) + " |",
               "|---|" + "---|" * len(MOTIONS)]
        for e in ENGINES:
            er = [r for r in rows if r["engine"] == e]
            cells = [fmt_cell(vals([r for r in er if r["motion"] == m], metric))
                     for m in MOTIONS]
            md.append(f"| {e} | " + " | ".join(cells) + " |")
            tables_json.setdefault("engine_x_motion", {}).setdefault(metric, {})[e] = {
                m: vals([r for r in er if r["motion"] == m], metric) for m in MOTIONS}

    # ---- 2. content-class and treatment breakdowns -------------------------
    md.append("\n## 2. Content-class breakdown (standard cells; frozen §8 table 2)")
    for metric, label in HEADLINES:
        md += ["", f"### {label}", "",
               "| engine | " + " | ".join(CLASSES) + " |",
               "|---|" + "---|" * len(CLASSES)]
        for e in ENGINES:
            er = [r for r in std if r["engine"] == e]
            cells = [fmt_cell(vals([r for r in er if r["content_class"] == c], metric))
                     for c in CLASSES]
            md.append(f"| {e} | " + " | ".join(cells) + " |")
            tables_json.setdefault("engine_x_class", {}).setdefault(metric, {})[e] = {
                c: vals([r for r in er if r["content_class"] == c], metric) for c in CLASSES}

    md.append("\n## 3. Treatment breakdown (standard cells; core 3×3 + A1 registers)")
    for metric, label in HEADLINES:
        md += ["", f"### {label}", "",
               "| engine | " + " | ".join(TREATMENTS) + " |",
               "|---|" + "---|" * len(TREATMENTS)]
        for e in ENGINES:
            er = [r for r in std if r["engine"] == e]
            cells = [fmt_cell(vals([r for r in er if r["treatment"] == t], metric))
                     for t in TREATMENTS]
            md.append(f"| {e} | " + " | ".join(cells) + " |")
            tables_json.setdefault("engine_x_treatment", {}).setdefault(metric, {})[e] = {
                t: vals([r for r in er if r["treatment"] == t], metric) for t in TREATMENTS}

    # ---- 3. frozen §8 hypothesis test --------------------------------------
    md += ["", "## 4. Pre-registered §8 test (FROZEN)",
           "",
           "Hypothesis: establishing panels degrade MORE than character/action "
           "panels on edge_decay |slope| and style_drift terminal. One-sided "
           "Mann–Whitney U (exact), establishing vs pooled cu+act, per engine; "
           "α = 0.05; rank-biserial r (+1 = every establishing cell above every "
           "other cell). **Small-n caveat: n_est = 12 vs n_rest = 21 per engine "
           "(32-cell Turbo: 12 vs 20); these are low-power comparisons and "
           "negative results are reported as registered, not as evidence of "
           "absence.**", ""]
    test = {}
    for basis_name, basis_rows in (
            ("primary_33cell", std),
            ("sensitivity_frozen27", [r for r in std
                                      if not r["panel_id"].startswith(("cip-", "chain-"))])):
        md += [f"### Basis: {basis_name}", "",
               "| engine | metric | n(est) | n(rest) | U | p (1-sided) | sig? | rank-biserial | med(est) | med(rest) |",
               "|---|---|---|---|---|---|---|---|---|---|"]
        for e in ENGINES:
            er = [r for r in basis_rows if r["engine"] == e]
            for metric in ("edge_abs_slope", "style_terminal"):
                t = mwu_est_vs_rest(er, metric)
                test.setdefault(basis_name, {}).setdefault(e, {})[metric] = t
                if t is None:
                    md.append(f"| {e} | {metric} | — | — | — | — | — | — | — | — |")
                    continue
                md.append(
                    f"| {e} | {metric} | {t['n_est']} | {t['n_rest']} | {t['U']:.0f} "
                    f"| {t['p_one_sided']:.4f} | {'**YES**' if t['significant_at_0.05'] else 'no'} "
                    f"| {t['rank_biserial']:+.2f} | {t['median_est']:.3g} | {t['median_rest']:.3g} |")
        md.append("")

    # ---- 4. exploratory: grey-ground covariate -----------------------------
    md += ["## 5. EXPLORATORY (not pre-registered): grey-ground covariate",
           "",
           "Spearman ρ between source-panel paper_white_p90 and each headline, "
           "line-only-treatment cells per engine (n = 9). Labelled exploratory: "
           "descriptive only, no α, hypothesis-generating for the taxonomy.", "",
           "| engine | " + " | ".join(m for m, _ in HEADLINES) + " |",
           "|---|" + "---|" * len(HEADLINES)]
    expl = {}
    for e in ENGINES:
        er = [r for r in std if r["engine"] == e and r["treatment"] == "line"]
        cells = []
        for metric, _ in HEADLINES:
            pairs = [(r["paper_white_p90"], r[metric]) for r in er
                     if r[metric] is not None and r["paper_white_p90"] is not None]
            if len(pairs) < 4:
                cells.append("—"); expl.setdefault(e, {})[metric] = None; continue
            x, y = zip(*pairs)
            rho, p = stats.spearmanr(x, y)
            expl.setdefault(e, {})[metric] = {"rho": float(rho), "p": float(p), "n": len(pairs)}
            cells.append(f"ρ={rho:+.2f} (n={len(pairs)})")
        md.append(f"| {e} | " + " | ".join(cells) + " |")

    (OUT / "tables.md").write_text("\n".join(md) + "\n")
    (OUT / "tables.json").write_text(json.dumps(tables_json, indent=1))
    (OUT / "prereg_test.json").write_text(json.dumps(
        {"frozen_ref": "docs/PREREGISTRATION.md §8", "alpha": ALPHA,
         "test": "one-sided Mann-Whitney U (exact), establishing > pooled cu+act",
         "results": test, "exploratory_grey_ground": expl}, indent=1))
    print(f"tables -> {OUT/'tables.md'}")
    print(f"test   -> {OUT/'prereg_test.json'}")

    # console: the verdict lines
    for e in ENGINES:
        for metric in ("edge_abs_slope", "style_terminal"):
            t = test["primary_33cell"][e][metric]
            if t:
                print(f"§8 {e:11s} {metric:15s} p={t['p_one_sided']:.4f} "
                      f"r_rb={t['rank_biserial']:+.2f} {'SIG' if t['significant_at_0.05'] else 'ns'}")


if __name__ == "__main__":
    main()
